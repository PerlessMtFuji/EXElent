"""Launcher generator — the entry point of every built EXE.

Does four things that PyInstaller does not do on its own:
1. registers all vendored `*.libs` directories for DLL loading,
2. sets the working directory so that relative paths in user code work,
3. catches every exception and shows it to the user instead of silently exiting,
4. keeps the console window (that it opened itself) alive so the output can be
   read after a double-click from Explorer.
"""

from __future__ import annotations

from exelent.models import AppKind, OutputMode

LAUNCHER_FILENAME = "_exelent_launcher.py"

_TEMPLATE = '''\
"""Generated by EXElent. Do not edit — this file is recreated on every build."""

import os
import runpy
import sys
import traceback

ENTRY_MODULE = {entry}


def _set_working_directory():
{chdir_body}


# `*.libs` directories next to packages are a delvewheel convention — that is
# where vendored native libraries live (numpy.libs, pandas.libs, scipy.libs…).
_DLL_DIRECTORIES = []


def _register_vendored_dll_dirs():
    """Adds all `*.libs` directories from the bundle to the DLL search path.

    Without this, numpy and pandas in the same program produce an EXE that dies
    with `DLL load failed while importing _multiarray_umath`. delvewheel vendors
    `msvcp140-<hash>.dll` into BOTH directories under the same filename;
    PyInstaller resolves binary dependencies by filename alone and takes the
    FIRST hit, so only the copy from `pandas.libs` ends up in the bundle and the
    numpy copy is missing entirely. At runtime delvewheel's hook in
    `numpy/__init__.py` registers only `numpy.libs` — pandas is imported LATER
    so nobody registers its directory, and the library sitting one directory away
    is unreachable.

    Registering ALL such directories upfront eliminates this entire class of
    errors, not just the numpy/pandas pair: scipy, matplotlib and opencv collide
    the same way, and the import order in someone else's code is not something
    EXElent can predict.

    The handles are kept in a module-level list — closing them would revoke the
    entry, so they must live as long as the program.
    """
    base = getattr(sys, "_MEIPASS", None)
    if not base or not hasattr(os, "add_dll_directory"):
        return
    try:
        names = sorted(os.listdir(base))
    except OSError:
        return
    for name in names:
        path = os.path.join(base, name)
        if not name.endswith(".libs") or not os.path.isdir(path):
            continue
        try:
            _DLL_DIRECTORIES.append(os.add_dll_directory(path))
        except OSError:
            pass


def _error_path():
    base = os.path.dirname(sys.executable)
    return os.path.join(base, "EXElent-error.txt")


def _save_report(text):
    try:
        with open(_error_path(), "w", encoding="utf-8") as handle:
            handle.write(text)
        return _error_path()
    except OSError:
        return None


def _show_error_dialog(text, saved_to):
    try:
        import tkinter
        from tkinter import scrolledtext

        window = tkinter.Tk()
        window.title("Program crashed")
        window.geometry("720x420")
        area = scrolledtext.ScrolledText(window, wrap="word")
        area.insert("1.0", text)
        area.configure(state="disabled")
        area.pack(fill="both", expand=True, padx=10, pady=(10, 0))

        def copy():
            window.clipboard_clear()
            window.clipboard_append(text)

        row = tkinter.Frame(window)
        row.pack(fill="x", padx=10, pady=10)
        tkinter.Button(row, text="Copy details", command=copy).pack(side="left")
        tkinter.Button(row, text="Close", command=window.destroy).pack(side="right")
        if saved_to:
            tkinter.Label(row, text="Saved to: " + saved_to).pack(side="left", padx=10)
        window.mainloop()
    except Exception:
        import ctypes

        ctypes.windll.user32.MessageBoxW(None, text, "Program error", 0x10)


def _owns_console():
    """Does this console window belong to us and will it close when we exit?

    A console program launched by double-clicking from Explorer gets its own
    window, which Windows closes the moment the process terminates — the user
    sees only a flash, even if the program printed something valuable. The same
    file launched from CMD, PowerShell or a pipe writes to SOMEONE ELSE's window
    that stays open; pausing for Enter there would just hang their automation.

    `GetConsoleProcessList` returns the number of processes attached to the
    console and distinguishes the two cases: 1 = we are alone, so the window is
    ours; 2 or more = there is a shell that launched us. When no answer is
    available (a windowed program without a console, another OS) we pick the
    safer choice: do not pause, because a hung program is worse than a closed
    window.
    """
    try:
        import ctypes

        buffer = (ctypes.c_uint * 8)()
        count = ctypes.windll.kernel32.GetConsoleProcessList(buffer, 8)
    except Exception:  # noqa: BLE001 - any failure means "do not pause"
        return False
    return count == 1


def _wait_for_keypress():
    if not _owns_console():
        return
    try:
        input("Press Enter to close...")
    except (EOFError, KeyboardInterrupt):
        pass


def _report(exc):
    text = "".join(traceback.format_exception(type(exc), exc, exc.__traceback__))
    saved_to = _save_report(text)
{report_body}


def main():
    _register_vendored_dll_dirs()
    _set_working_directory()
    try:
        runpy.run_module(ENTRY_MODULE, run_name="__main__", alter_sys=True)
    except SystemExit:
        raise
    except BaseException as exc:  # noqa: BLE001 - the launcher must catch everything
        _report(exc)
        sys.exit(1)
    finally:
{finish_body}


if __name__ == "__main__":
    main()
'''

# cwd points to the PERSISTENT EXE directory in BOTH modes (B01). Previously
# ONEFILE chdir'd to `sys._MEIPASS` — the temporary extraction directory that
# PyInstaller deletes on process exit. Every relative write
# (`open('result.txt','w')`, `Image.save('out.png')`) landed there and vanished
# along with the directory. The EXE directory is persistent, so writes survive —
# even when the heuristic did not detect that the program writes at all.
#
# The trade-off applies ONLY to ONEFILE: bundled resources live in `_MEIPASS`,
# so a read via a relative path (`open('config.json')`) may not find the file.
# That is why the recommended and default mode is ONEDIR (resources sit next to
# the EXE), and the manual ONEFILE choice carries a visible warning
# (`planning.onefile_limitation_issues` -> `onefile_no_resource_guarantee`).
_CHDIR_EXECUTABLE = """\
    os.chdir(os.path.dirname(os.path.abspath(sys.executable)))
"""

_REPORT_WINDOWED = """\
    _show_error_dialog(text, saved_to)
"""

_REPORT_CONSOLE = """\
    print(text, file=sys.stderr)
    if saved_to:
        print("Details saved to: " + saved_to, file=sys.stderr)
"""

# The pause at the end of `main()` covers both successful and failed runs —
# if the error report paused for Enter on its own, a crash would require
# pressing it twice.
_FINISH_CONSOLE = """\
        _wait_for_keypress()
"""

_FINISH_WINDOWED = """\
        pass
"""


def _quote_module_name(value: str) -> str:
    # Why not repr()? It picks single quotes for a plain identifier, which
    # fails the test suite's double-quote assertion.
    #
    # Why not json.dumps()? It escapes astral code points (above U+FFFF) as
    # a UTF-16 surrogate pair of \uXXXX escapes, per the JSON spec. Python's
    # string-literal grammar does NOT recombine adjacent \u surrogate
    # escapes back into one scalar value, so ENTRY_MODULE would silently
    # decode to two lone-surrogate characters instead of the original one
    # character -- a corrupted round trip that still parses.
    #
    # str.encode("unicode_escape") escapes an astral code point as a single
    # \U000XXXXX escape instead, which Python's grammar *does* decode back
    # to the original scalar. It does not escape a literal double quote
    # though, so that is handled separately below, after the unicode_escape
    # pass (so a backslash it introduces is never re-escaped).
    escaped = value.encode("unicode_escape").decode("ascii")
    escaped = escaped.replace('"', '\\"')
    return '"' + escaped + '"'


def render_launcher(entry_module: str, app_kind: AppKind, output_mode: OutputMode) -> str:
    # `output_mode` no longer branches the working directory — both modes anchor
    # cwd in the persistent EXE directory (see comment at `_CHDIR_EXECUTABLE`).
    # The parameter stays in the contract: the build passes it, and the split
    # between script and package launch comes back in B03.
    _ = output_mode
    chdir_body = _CHDIR_EXECUTABLE
    windowed = app_kind is AppKind.WINDOWED
    report_body = _REPORT_WINDOWED if windowed else _REPORT_CONSOLE
    finish_body = _FINISH_WINDOWED if windowed else _FINISH_CONSOLE
    return _TEMPLATE.format(
        entry=_quote_module_name(entry_module),
        chdir_body=chdir_body,
        report_body=report_body,
        finish_body=finish_body,
    )
